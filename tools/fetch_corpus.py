"""Select a diverse >=N-tune v1 HVSC corpus and emit tests/_corpus.py.

Uses pysidtracker's ``resolve_tune`` to fetch candidates round-robin across a
broad composer set, keeps PSID tunes with a per-frame ``play`` driver (v1), and
writes the accepted relpaths as ``.sid`` literals for the fetch machinery.
"""

