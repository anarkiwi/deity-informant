"""Generate ``crates/di-pcode/src/templates_gen.rs`` from ``deity_informant.lifter.template``.

Each opcode's template binds every operand-derived constant to an operand slot; see
docs/native.md.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from jennings.opcodes import OPCODES as OPS

from deity_informant.lifter import template

OUT = Path(__file__).resolve().parent.parent / "crates/di-pcode/src/templates_gen.rs"
SLOTS = {
    ((1,), "id"): "B1",
    ((1, 2), "word"): "Word",
    ((1,), "hi1"): "B1Inc",
    ((2,), "hi1"): "B2Inc",
}
OPC = {
    "COPY": "Copy",
    "INT_ZEXT": "IntZext",
    "INT_ADD": "IntAdd",
    "INT_SUB": "IntSub",
    "INT_AND": "IntAnd",
    "INT_OR": "IntOr",
    "INT_XOR": "IntXor",
    "INT_LEFT": "IntLeft",
    "INT_RIGHT": "IntRight",
    "INT_EQUAL": "IntEqual",
    "INT_NOTEQUAL": "IntNotEqual",
    "INT_LESS": "IntLess",
    "INT_LESSEQUAL": "IntLessEqual",
    "INT_CARRY": "IntCarry",
    "LOAD": "Load",
    "STORE": "Store",
}
CTRL = {
    "next": "Next",
    "jmp": "Jmp",
    "jmpind": "JmpInd",
    "jsr": "Jsr",
    "rts": "Rts",
    "rti": "Rti",
    "brk": "Brk",
    "jam": "Jam",
}
PEN = {None: "None", "branch": "Branch", "ax": "Ax", "ay": "Ay", "iy": "Iy"}


def _vn(vn, slot=None):
    if vn is None:
        return "Vn::NONE"
    sp, off, sz = vn
    if sp == "c":
        return "cs(Slot::%s, %d)" % (slot, sz) if slot else "c(0x%x, %d)" % (off, sz)
    if sp == "r":
        assert sz == 1, vn
        return "r(%d)" % off
    assert sp == "u", vn
    return "u(%d, %d)" % (off, sz)


def _ops(t):
    slot = {k: SLOTS[v] for k, v in t.prov.items()}
    return [
        "    Op::new(O::%s, %s, %s, %s),"
        % (
            OPC[mn],
            _vn(out),
            _vn(ins[0], slot.get((i, 0))),
            _vn(ins[1] if len(ins) > 1 else None, slot.get((i, 1))),
        )
        for i, (mn, out, ins) in enumerate(t.ops)
    ]


def _row(op, t, start, bind):
    ctrl, pen = t.ctrl, t.pen or (None,)
    if ctrl[0] == "br":
        kind = "CtrlKind::Br { flag: %d, pol: %d }" % ctrl[1:]
    else:
        kind = "CtrlKind::" + CTRL[ctrl[0]]
    return (
        "    Template { start: %d, n: %d, bind: %d, nbind: %d, len: %d, cyc: %d, "
        "pen: PenKind::%s, ctrl: %s, iy_base: %d }, // %02X %s %s"
        % (
            start,
            len(t.ops),
            bind,
            len(t.prov),
            t.len,
            t.cyc,
            PEN[pen[0]],
            kind,
            pen[1] if pen[0] == "iy" else 0,
            op,
            *OPS[op],
        )
    )


HEADER = """\
// Generated by tools/gen_pcode.py from deity_informant.lifter; do not edit.

use crate::ir::{c, cs, r, u, CtrlKind, Op, Opc as O, PenKind, Slot, Template, Vn};
"""


def generate() -> str:
    pool, table, binds, start = [], [], [], 0
    for op in range(256):
        t = template(op)
        pool.append("    // %02X %s %s" % (op, *OPS[op]))
        pool += _ops(t)
        table.append(_row(op, t, start, len(binds)))
        binds += sorted(i << 1 | j for i, j in t.prov)
        start += len(t.ops)
    uniq = max(
        vn[1] + vn[2]
        for op in range(256)
        for _mn, out, ins in template(op).ops
        for vn in (out, *ins)
        if vn is not None and vn[0] == "u"
    )
    out = [
        HEADER,
        "/// Unique-space words an instruction needs.",
        "pub const UNIQUE_SIZE: usize = %d;" % uniq,
        "",
        "/// Every opcode's op templates, concatenated.",
        "pub static OPS: [Op; %d] = [" % start,
        *pool,
        "];",
        "",
        "/// Every opcode's operand-bound input positions (`op << 1 | input`), concatenated.",
        "pub static BINDS: [u8; %d] = [" % len(binds),
        *("    %s," % ", ".join(map(str, binds[i : i + 16])) for i in range(0, len(binds), 16)),
        "];",
        "",
        "/// Per-opcode templates.",
        "pub static TEMPLATES: [Template; 256] = [",
        *table,
        "];",
    ]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the checked-in file is stale")
    args = ap.parse_args(argv)
    src = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != src:
            print("%s is stale; run tools/gen_pcode.py" % OUT, file=sys.stderr)
            return 1
        return 0
    OUT.write_text(src)
    return 0


if __name__ == "__main__":
    sys.exit(main())
